using FinanceManager.Infrastructure.Persistence;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Migrations;

namespace FinanceManager.Tests.Unit.Api.Migrations;

[Trait("Category", "Unit")]
public class DividendPaymentMigrationTests
{
    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public void MigrationCreatesProviderCompatibleLedgerAndReversibleForeignKeys(bool sqlServer)
    {
        var options = new DbContextOptionsBuilder<AppDbContext>();
        if (sqlServer) options.UseSqlServer("Server=localhost;Database=script-only;Trusted_Connection=True", b => b.MigrationsAssembly("FinanceManager.Api"));
        else options.UseNpgsql("Host=localhost;Database=script-only", b => b.MigrationsAssembly("FinanceManager.Api"));
        using var context = new AppDbContext(options.Options);
        var migrator = context.GetService<IMigrator>();
        var up = migrator.GenerateScript("AllowIncompleteAssetListings", "AddDividendPayments");
        var down = migrator.GenerateScript("AddDividendPayments", "AllowIncompleteAssetListings");
        Assert.Contains("CREATE TABLE", up);
        Assert.Contains("DividendPayments", up);
        Assert.Contains("ON DELETE CASCADE", up);
        Assert.Contains("FK_DividendPayments_AssetListings_AssetListingId", up);
        Assert.Contains(sqlServer ? "IDENTITY" : "GENERATED BY DEFAULT AS IDENTITY", up);
        Assert.Contains(sqlServer ? "decimal(18,8)" : "numeric(18,8)", up);
        Assert.Contains(sqlServer ? "datetimeoffset" : "timestamp with time zone", up);
        Assert.Contains("DROP TABLE", down);
        Assert.Contains("DividendPayments", down);
    }
}